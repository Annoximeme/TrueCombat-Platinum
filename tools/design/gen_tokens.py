#!/usr/bin/env python3
"""Writes the design tokens in tokens.json to every surface that uses them.

  python tools/design/gen_tokens.py            # website block in docs/style.css + files in tools/design/out/
  python tools/design/gen_tokens.py --check    # exit 1 when a generated file is out of date

Outputs (tools/design/out/ is copied into the game and launcher trees by the visual-ux kit):
  docs/style.css            the colour/type variables between the  tokens:begin / tokens:end  markers
  out/tokens.css            the same variables as a standalone sheet
  tools/staff-portal/static/style.css   the variables between the tokens markers (portal extras follow)
  out/platinum_tokens.h     C: COLORREF values (launcher, Win32 RGB) and float[4] values (cgame HUD)
  out/platinum_tokens.py    in-game menu colour strings for analysis_scripts/platinum_style.py
  out/tokens.json           flat name -> hex map for the Discord bot cards
"""
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = HERE / "out"
T = json.loads((HERE / "tokens.json").read_text(encoding="utf-8"))
COL = {k: v["hex"] for k, v in T["color"].items()}
GAME = {k: v for k, v in T["game"].items() if not k.startswith("_")}
CSS_NAMES = {"bg": "bg", "panel": "panel", "panel2": "panel-2", "line": "line", "fg": "fg", "muted": "muted", "dim": "dim",
             "red": "red", "redHi": "red-hi", "amber": "amber", "ok": "ok"}
STAMP = "Generated by tools/design/gen_tokens.py from tools/design/tokens.json. Do not edit by hand."


def rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def snake(k):
    return re.sub(r"([A-Z])", r"_\1", k).upper()


def css_block(indent="  ", extra=True):
    lines = ["%s/* tokens:begin (%s) */" % (indent, STAMP)]
    for k, name in CSS_NAMES.items():
        lines.append("%s--%s: %s;" % (indent, name, COL[k]))
    if extra:
        for k in ("ink", "panel2", "lineHot", "steel", "redEdge", "danger", "staff", "teamTerrorists", "teamSpecops"):
            lines.append("%s--t-%s: %s;" % (indent, re.sub(r"([A-Z])", r"-\1", k).lower(), COL[k]))
    f = T["font"]
    lines.append('%s--f-display: "%s", "Arial Narrow", "Roboto Condensed", sans-serif;' % (indent, f["display"]["family"]))
    lines.append('%s--f-body: "%s", "Segoe UI", system-ui, sans-serif;' % (indent, f["body"]["family"]))
    lines.append('%s--f-mono: "%s", "Cascadia Mono", Consolas, monospace;' % (indent, f["mono"]["family"]))
    m = T["motion"]
    lines.append("%s--t-fast: %dms; --t-base: %dms; --t-slow: %dms; --t-ease: cubic-bezier(%s);" % (indent, m["fast"], m["base"], m["slow"], ", ".join("%g" % x for x in m["ease"])))
    lines.append("%s/* tokens:end */" % indent)
    return "\n".join(lines)


def website(text):
    block = css_block()
    if "tokens:begin" in text:
        return re.sub(r"[ \t]*/\* tokens:begin.*?tokens:end \*/", block, text, count=1, flags=re.S)
    # first run: replace the hand-written colour and font variables at the top of :root
    start = text.index(":root {") + len(":root {\n")
    end = text.index("  --step--1:", start)
    return text[:start] + block + "\n\n" + text[end:]


def portal(text):
    """Staff portal stylesheet: the shared block, then the portal's own extra variables."""
    block = css_block(extra=False)
    if "tokens:begin" in text:
        return re.sub(r"[ \t]*/\* tokens:begin.*?tokens:end \*/", lambda m: block, text, count=1, flags=re.S)
    start = text.index(":root {") + len(":root {\n")
    end = text.index("  --t-red:", start)
    extras = "  --line-hi: #344055; --blue: #5b9bd5; --staff: #ff9914;\n"
    return text[:start] + block + "\n" + extras + text[end:]


def c_header():
    out = ["/* %s */" % STAMP, "#ifndef PLATINUM_TOKENS_H", "#define PLATINUM_TOKENS_H", ""]
    out.append("/* Win32 COLORREF (launcher). Needs <windows.h> for RGB(). */")
    out.append("#ifdef RGB")
    for k, h in COL.items():
        r, g, b = rgb(h)
        out.append("#define TOK_%s RGB(%d,%d,%d)" % (snake(k), r, g, b))
    out.append("#endif")
    out.append("")
    out.append("/* Linear 0..1 RGBA (cgame HUD, menus drawn in C). */")
    for k, h in COL.items():
        r, g, b = rgb(h)
        out.append("#define TOK_%s_F %.3ff,%.3ff,%.3ff" % (snake(k), r / 255, g / 255, b / 255))
    for k, v in T["alpha"].items():
        out.append("#define TOK_A_%s %.2ff" % (snake(k), v))
    out.append("")
    out.append("/* In-game menus and HUD (Direction A), exact. */")
    for k, v in GAME.items():
        out.append("#define TOK_GAME_%s_F %s" % (snake(k), ",".join(x + "f" for x in v.split())))
    s = T["shape"]
    out.append("#define TOK_RADIUS %d" % s["radius"])
    out.append("#define TOK_RADIUS_LAUNCHER %d" % s["radiusLauncher"])
    out.append("#define TOK_TICK %d" % s["tick"])
    out.append("#define TOK_TICK_WEIGHT %d" % s["tickWeight"])
    out.append("#define TOK_MS_FAST %d" % T["motion"]["fast"])
    out.append("#define TOK_MS_BASE %d" % T["motion"]["base"])
    out.append("#define TOK_MS_SLOW %d" % T["motion"]["slow"])
    out += ["", "#endif", ""]
    return "\n".join(out)


def py_module():
    out = ['"""%s"""' % STAMP, ""]
    for k, h in COL.items():
        r, g, b = rgb(h)
        out.append("%s = '%.3f %.3f %.3f'" % (snake(k), r / 255, g / 255, b / 255))
    out.append("HEX = %s" % json.dumps(COL, indent=4))
    out.append("ALPHA = %s" % json.dumps(T["alpha"]))
    out.append("FONT = %s" % json.dumps({k: v["family"] for k, v in T["font"].items()}))
    out.append("# in-game menus and HUD (Direction A), exact menu colour strings")
    out.append("GAME = %s" % json.dumps({snake(k): v for k, v in GAME.items()}, indent=4))
    return "\n".join(out) + "\n"


def outputs():
    css = (ROOT / "docs" / "style.css").read_text(encoding="utf-8")
    return {
        ROOT / "docs" / "style.css": website(css),
        ROOT / "tools" / "staff-portal" / "static" / "style.css": portal((ROOT / "tools" / "staff-portal" / "static" / "style.css").read_text(encoding="utf-8")),
        OUT / "tokens.css": "/* %s */\n:root {\n%s\n}\n" % (STAMP, css_block()),
        OUT / "platinum_tokens.h": c_header(),
        OUT / "platinum_tokens.py": py_module(),
        OUT / "tokens.json": json.dumps({"_about": STAMP, **COL}, indent=2) + "\n",
    }


def main():
    check = "--check" in sys.argv
    stale = []
    for path, text in outputs().items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            stale.append(path)
            if not check:
                path.parent.mkdir(exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    if check and stale:
        sys.exit("out of date: " + ", ".join(str(p.relative_to(ROOT)) for p in stale))
    print("tokens: %d file(s) %s" % (len(stale), "stale" if check else "written"))


if __name__ == "__main__":
    main()
